CREATE OR REPLACE FUNCTION validar_pago()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    precio_paquete numeric(12, 2);
    moneda_paquete char(3);
BEGIN
    SELECT precio_real, codigo_moneda
      INTO precio_paquete, moneda_paquete
      FROM paquetes_moneda
     WHERE paquete_moneda_id = NEW.paquete_moneda_id;

    IF NEW.importe <> precio_paquete OR NEW.codigo_moneda <> moneda_paquete THEN
        RAISE EXCEPTION 'El importe o la moneda del pago no coincide con el paquete';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_pago
BEFORE INSERT OR UPDATE OF paquete_moneda_id, importe, codigo_moneda
ON pagos
FOR EACH ROW EXECUTE FUNCTION validar_pago();

CREATE TABLE movimientos_cartera (
    movimiento_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint NOT NULL REFERENCES carteras(usuario_id) ON DELETE RESTRICT,
    compra_id bigint UNIQUE,
    pago_id bigint UNIQUE,
    actor_id bigint REFERENCES usuarios(usuario_id) ON DELETE RESTRICT,
    motivo_ajuste varchar(500),
    cantidad bigint NOT NULL CHECK (cantidad <> 0),
    tipo varchar(16) NOT NULL CHECK (tipo IN ('credito', 'debito', 'ajuste')),
    clave_idempotencia varchar(160) NOT NULL UNIQUE,
    creado_en timestamptz NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(compra_id, pago_id) <= 1),
    CHECK ((tipo = 'credito' AND cantidad > 0)
        OR (tipo = 'debito' AND cantidad < 0)
        OR tipo = 'ajuste'),
    CHECK (tipo <> 'ajuste' OR (actor_id IS NOT NULL AND motivo_ajuste IS NOT NULL)),
    FOREIGN KEY (compra_id, usuario_id)
        REFERENCES compras_tienda(compra_id, usuario_id) ON DELETE RESTRICT,
    FOREIGN KEY (pago_id, usuario_id)
        REFERENCES pagos(pago_id, usuario_id) ON DELETE RESTRICT
);

CREATE OR REPLACE FUNCTION validar_movimiento_cartera()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    costo_compra integer;
    cantidad_paquete integer;
BEGIN
    IF NEW.compra_id IS NOT NULL THEN
        SELECT costo_moneda_virtual
          INTO costo_compra
          FROM compras_tienda
         WHERE compra_id = NEW.compra_id;
        IF NEW.tipo <> 'debito' OR NEW.cantidad <> -costo_compra THEN
            RAISE EXCEPTION 'El movimiento no coincide con la compra asociada';
        END IF;
    ELSIF NEW.pago_id IS NOT NULL THEN
        SELECT pm.cantidad_moneda
          INTO cantidad_paquete
          FROM pagos p
          JOIN paquetes_moneda pm ON pm.paquete_moneda_id = p.paquete_moneda_id
         WHERE p.pago_id = NEW.pago_id;
        IF NEW.tipo <> 'credito' OR NEW.cantidad <> cantidad_paquete THEN
            RAISE EXCEPTION 'El movimiento no coincide con el pago asociado';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_movimiento_cartera
BEFORE INSERT OR UPDATE OF compra_id, pago_id, cantidad, tipo
ON movimientos_cartera
FOR EACH ROW EXECUTE FUNCTION validar_movimiento_cartera();

CREATE OR REPLACE FUNCTION actualizar_saldo_cartera()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    saldo_actual bigint;
BEGIN
    SELECT saldo INTO saldo_actual
      FROM carteras
     WHERE usuario_id = NEW.usuario_id
     FOR UPDATE;

    IF saldo_actual + NEW.cantidad < 0 THEN
        RAISE EXCEPTION 'Saldo insuficiente para el movimiento de cartera';
    END IF;

    UPDATE carteras
       SET saldo = saldo + NEW.cantidad,
           actualizado_en = now()
     WHERE usuario_id = NEW.usuario_id;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_actualizar_saldo_cartera
AFTER INSERT ON movimientos_cartera
FOR EACH ROW EXECUTE FUNCTION actualizar_saldo_cartera();

