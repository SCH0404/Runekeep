CREATE OR REPLACE FUNCTION validar_compra_tienda()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    precio_publicado integer;
BEGIN
    SELECT precio_moneda_virtual
      INTO precio_publicado
      FROM publicaciones_tienda
     WHERE publicacion_tienda_id = NEW.publicacion_tienda_id;

    IF precio_publicado IS NULL OR NEW.costo_moneda_virtual <> precio_publicado THEN
        RAISE EXCEPTION 'El costo de la compra no coincide con la publicación de tienda';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_compra_tienda
BEFORE INSERT OR UPDATE OF publicacion_tienda_id, costo_moneda_virtual
ON compras_tienda
FOR EACH ROW EXECUTE FUNCTION validar_compra_tienda();

