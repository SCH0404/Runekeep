CREATE OR REPLACE FUNCTION validar_publicacion_comunitaria()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.visibilidad = 'comunidad'
       AND NOT EXISTS (
           SELECT 1
             FROM comunidades c
             LEFT JOIN membresias_comunidad m
               ON m.comunidad_id = c.comunidad_id
              AND m.usuario_id = NEW.autor_id
              AND m.estado = 'aceptada'
            WHERE c.comunidad_id = NEW.comunidad_id
              AND (c.creador_id = NEW.autor_id OR m.usuario_id IS NOT NULL)
       ) THEN
        RAISE EXCEPTION 'El autor no tiene acceso a la comunidad';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_publicacion_comunitaria
BEFORE INSERT OR UPDATE OF autor_id, comunidad_id, visibilidad
ON publicaciones
FOR EACH ROW EXECUTE FUNCTION validar_publicacion_comunitaria();

